#!/usr/bin/env node
// Brings the design's drawings into the kit: the 16px icon set, the duotone family and the empty-state
// illustrations, each drawn in `docs/design/build/` (icons.mjs, duotone.mjs, illustrations.mjs) as this
// product's own. The generator is source (README item 10); this script reads it and writes
// `packages/design-system/src/drawings.tsx` — the kit's copy — as JSX symbols, so the four apps never
// import from docs/ and the design session's next redraw reaches the product by running this again.
//
//   node scripts/import-drawings.mjs            # rewrites drawings.tsx
//   node scripts/import-drawings.mjs --check    # exits 1 if drawings.tsx is behind the generator
//
// SVG geometry is out of the literal gate's scope by the design's own rule; nothing here is a colour.
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { join } from 'node:path';

const REPO = fileURLToPath(new URL('..', import.meta.url));
const BUILD = join(REPO, 'docs', 'design', 'build');
const OUT = process.env['DRAWINGS_OUT'] ?? join(REPO, 'packages', 'design-system', 'src', 'drawings.tsx');

const icons = await import(pathToFileURL(join(BUILD, 'icons.mjs')).href);
const duo = await import(pathToFileURL(join(BUILD, 'duotone.mjs')).href);
const illo = await import(pathToFileURL(join(BUILD, 'illustrations.mjs')).href);

/** An SVG attribute as JSX writes it. @type {Readonly<Record<string, string>>} */
const ATTR = { class: 'className', 'stroke-width': 'strokeWidth', 'stroke-dasharray': 'strokeDasharray', 'stroke-linecap': 'strokeLinecap', 'stroke-linejoin': 'strokeLinejoin', 'fill-rule': 'fillRule', 'clip-rule': 'clipRule' };
/** @param {string} markup the inner markup of one symbol, as the generator emits it */
function toJsx(markup) {
  return markup
    .replace(/<(\w+)([^>]*?)\s*\/>/g, (_, tag, attrs) => `<${tag}${jsxAttrs(attrs)} />`)
    .replace(/<(\w+)([^>]*)>/g, (m, tag, attrs) => (m.endsWith('/>') ? m : `<${tag}${jsxAttrs(attrs)}>`));
}
/** @param {string} attrs */
function jsxAttrs(attrs) {
  return attrs.replace(/\s([a-z-]+)="([^"]*)"/g, (_, /** @type {string} */ name, /** @type {string} */ value) => ` ${ATTR[name] ?? name}="${value}"`);
}
/** @param {string} id @param {string} viewBox @param {string} inner @param {string} [cls] */
const symbol = (id, viewBox, inner, cls = '') =>
  `      <symbol id="${id}" viewBox="${viewBox}"${cls ? ` className="${cls}"` : ''}>\n        ${toJsx(inner)}\n      </symbol>`;

// icons.mjs keeps its paths in a private table; the sprite it emits is the public surface, so read that
const iconSprite = icons.iconSprite();
const ICONS = [...iconSprite.matchAll(/<symbol id="i-([a-z-]+)" viewBox="0 0 16 16">([\s\S]*?)<\/symbol>/g)].map((m) => [m[1], m[2]]);
const duoSprite = duo.duoSprite();
const DUOS = [...duoSprite.matchAll(/<symbol id="d-([a-z-]+)" viewBox="0 0 24 24" class="duo-art">([\s\S]*?)<\/symbol>/g)].map((m) => [m[1], m[2]]);
const illoSprite = illo.illoSymbols();
const ILLOS = [...illoSprite.matchAll(/<symbol id="illo-([a-z-]+)" viewBox="0 0 160 160" class="illo-art">([\s\S]*?)<\/symbol>/g)].map((m) => [m[1], m[2]]);
if (ICONS.length !== icons.ICON_NAMES.length || DUOS.length !== duo.DUO_NAMES.length || ILLOS.length !== illo.ILLO_SUBJECTS.length) {
  throw new Error(`the generator's sprites did not parse whole: ${ICONS.length}/${icons.ICON_NAMES.length} icons, ${DUOS.length}/${duo.DUO_NAMES.length} duotones, ${ILLOS.length}/${illo.ILLO_SUBJECTS.length} illustrations`);
}
/** @param {readonly string[]} names */
const list = (names) => names.map((n) => `  '${n}',`).join('\n');
/** @param {Readonly<Record<string, string>>} obj */
const record = (obj) => Object.entries(obj).map(([k, v]) => `  '${k}': '${v}',`).join('\n');

const out = `/* Generated by scripts/import-drawings.mjs from docs/design/build/{icons,duotone,illustrations}.mjs — do not edit;
   run the script. ${ICONS.length} icons on the 16px grid, ${DUOS.length} duotones on 24, ${ILLOS.length} illustrations on 160. */
import type { ReactNode } from 'react';

export const ICON_NAMES = [
${list(icons.ICON_NAMES)}
] as const;
export type IconName = (typeof ICON_NAMES)[number];

export const DUOTONE_NAMES = [
${list(duo.DUO_NAMES)}
] as const;
export type DuotoneName = (typeof DUOTONE_NAMES)[number];

/** The subjects drawn — one drawing per subject. */
export const ILLUSTRATION_SUBJECTS = [
${list(illo.ILLO_SUBJECTS)}
] as const;
export type IllustrationSubject = (typeof ILLUSTRATION_SUBJECTS)[number];

/** Each empty state's name → the subject it draws (ILLO_FOR in illustrations.mjs). */
export const ILLUSTRATION_FOR = {
${record(illo.ILLO_FOR)}
} as const satisfies Record<string, IllustrationSubject>;
export type IllustrationName = keyof typeof ILLUSTRATION_FOR;
export const ILLUSTRATION_NAMES = Object.keys(ILLUSTRATION_FOR) as readonly IllustrationName[];

/** What each subject is, for a reader (ILLO_CAPTION). */
export const ILLUSTRATION_CAPTION = {
${record(illo.ILLO_CAPTION)}
} as const satisfies Record<IllustrationSubject, string>;

/** A monoline icon's name → the duotone that does its job on a disc (DUO_FOR_ICON). */
export const DUOTONE_FOR_ICON = {
${record(duo.DUO_FOR_ICON)}
} as const satisfies Record<string, DuotoneName>;

/** Every symbol, inside one hidden svg; \`Sprite\` renders it once per document. */
export function DrawingSymbols(): ReactNode {
  return (
    <>
${ICONS.map(([n, inner]) => symbol(`i-${n}`, '0 0 16 16', inner)).join('\n')}
${DUOS.map(([n, inner]) => symbol(`d-${n}`, '0 0 24 24', inner, 'duo-art')).join('\n')}
${ILLOS.map(([n, inner]) => symbol(`illo-${n}`, '0 0 160 160', inner, 'illo-art')).join('\n')}
    </>
  );
}
`;
if (process.argv.includes('--check')) {
  const current = readFileSync(OUT, 'utf8');
  if (current !== out) {
    process.stderr.write(`${OUT} is behind docs/design/build — run node scripts/import-drawings.mjs\n`);
    process.exit(1);
  }
  process.stdout.write('drawings.tsx matches the generator\n');
} else {
  writeFileSync(OUT, out, 'utf8');
  process.stdout.write(`wrote ${OUT}: ${ICONS.length} icons, ${DUOS.length} duotones, ${ILLOS.length} illustrations\n`);
}
